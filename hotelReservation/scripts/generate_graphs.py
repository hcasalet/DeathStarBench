# Read a subset of the file as a multiline string
def read_subset_from_file(file_path, start_line=0, end_line=None):
    with open(file_path, 'r') as f:
        lines = f.readlines()
        if end_line is None:
            end_line = len(lines)
        subset = ''.join(lines[start_line:end_line])
    return subset

# Example usage: replace with your actual file path and desired line range
file_path = '/users/eirn/DeathStarBench/hotelReservation/scripts/baseline/run_1/throughput_18000.txt'

raw_data = read_subset_from_file(file_path, start_line=43, end_line=123)

# Parse the data
latencies = []
percentiles = []

pattern = re.compile(r"^\s*([\d.]+)\s+([\d.]+)\s+\d+\s+[\d.]+", re.MULTILINE)
for match in pattern.finditer(raw_data):
    latency = float(match.group(1))
    percentile = float(match.group(2))
    latencies.append(latency)
    percentiles.append(percentile)

# Plot the CDF
plt.figure(figsize=(10, 6))
plt.plot(latencies, [p * 100 for p in percentiles], marker='o', linestyle='-', color='blue')
plt.title("CDF of Request Latency")
plt.xlabel("Latency (ms)")
plt.ylabel("Cumulative Percentile (%)")
plt.grid(True)
plt.tight_layout()
plt.savefig("latency_cdf.png")
